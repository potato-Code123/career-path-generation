"""Acquire and pin the upstream source files, and expose readers for them.

Downloads each source into ``data/raw/`` and records ``url``, ``sha256``,
``retrieved_utc`` and ``release_label`` in ``data/raw/SOURCE_MANIFEST.yaml``.
Re-running verifies the hash of every file already present and skips the
download; a hash mismatch is a hard error, never a silent re-fetch.

This module is also the single place that knows how the raw bytes are laid out
-- which member of the O*NET zip holds job titles, which sheet of the crosswalk
holds CIP->SOC. Every downstream build script reads through the accessors here
rather than re-deriving those paths, so ``data/raw/`` stays untouched on disk.

Manual sources
--------------
``bls.gov`` refuses automated retrieval from most hosts (HTTP 403 with an
"Access Denied / bot activity" page on every path, including directory
listings). That is a transport refusal, not a missing release, so the SOC
structure file is registered as a manual source: the URL is recorded for
provenance, and the fetcher reports precise instructions instead of
substituting a different release.
"""

