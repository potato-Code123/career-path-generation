MANIFEST_PATH = RAW_DIR / "SOURCE_MANIFEST.yaml"

_ONET_RELEASE = "O*NET 30.3 Database (May 2026 Release)"
_USER_AGENT = "occupational-scrape/0.2 (degree-planning research; contact repository owner)"


class SourceHashMismatch(RuntimeError):
    """A file on disk does not match the sha256 pinned in the manifest."""


class MissingManifestEntry(RuntimeError):
    """A source has no manifest entry, so its bytes cannot be verified."""


class ManualSourceMissing(RuntimeError):
    """A manually-acquired source is not present in ``data/raw/``."""


@dataclass(frozen=True)
class SourceFile:
    key: str
    filename: str
    url: str
    release_label: str
    manual: bool = False
    manual_instructions: str = ""


SOURCES: tuple[SourceFile, ...] = (
    SourceFile(
        key="onet_database",
        filename="db_30_3_text.zip",
        url="https://www.onetcenter.org/dl_files/database/db_30_3_text.zip",
        release_label=_ONET_RELEASE,
    ),
    SourceFile(
        key="onet_all_occupations",
        filename="All_Occupations.csv",
        url="https://www.onetonline.org/find/all?fmt=csv",
        release_label="O*NET OnLine All Occupations export (site release 30.3)",
    ),
    SourceFile(
        key="bls_soc_structure",
        filename="soc_structure_2018.xlsx",
        url="https://www.bls.gov/soc/2018/soc_structure_2018.xlsx",
        release_label="BLS SOC 2018 structure",
        manual=True,
        manual_instructions=(
            "bls.gov returns HTTP 403 to automated clients from this host. Open\n"
            "  https://www.bls.gov/soc/2018/soc_structure_2018.xlsx\n"
            "in a browser and save it to data/raw/soc_structure_2018.xlsx, then\n"
            "re-run this script to hash and pin it."
        ),
    ),
    SourceFile(
        key="cip_soc_crosswalk",
        filename="CIP2020_SOC2018_Crosswalk.xlsx",
        url="https://nces.ed.gov/ipeds/cipcode/Files/CIP2020_SOC2018_Crosswalk.xlsx",
        release_label="NCES CIP 2020 to SOC 2018 Crosswalk",
    ),
)

_BY_KEY = {source.key: source for source in SOURCES}


# --------------------------------------------------------------------------
# Acquisition
# --------------------------------------------------------------------------


def raw_path(key: str) -> Path:
    """Absolute path of a registered source in ``data/raw/``."""
    return RAW_DIR / _BY_KEY[key].filename


def read_manifest() -> dict[str, dict]:
    if not MANIFEST_PATH.exists():
        return {}
    loaded = yaml.safe_load(MANIFEST_PATH.read_text()) or {}
    return {entry["key"]: entry for entry in loaded.get("sources", [])}


def _write_manifest(entries: dict[str, dict]) -> None:
    ordered = [entries[source.key] for source in SOURCES if source.key in entries]
    MANIFEST_PATH.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST_PATH.write_text(
        "# Provenance record for data/raw/. Generated by fetch_source_files.py.\n"
        "# Hashes are pinned: a mismatch on re-run is a hard error, never a re-fetch.\n"
        + yaml.safe_dump({"sources": ordered}, sort_keys=False, default_flow_style=False)
    )


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _download(source: SourceFile, destination: Path) -> None:
    response = requests.get(
        source.url, timeout=300, stream=True, headers={"User-Agent": _USER_AGENT}
    )
    if response.status_code == 404:
        raise RuntimeError(
            f"{source.key}: {source.url} returned 404. The pinned release is gone; "
            "stop and resolve this rather than substituting another release."
        )
    if response.status_code == 403:
        raise RuntimeError(
            f"{source.key}: {source.url} returned 403 (automated retrieval refused). "
            "Acquire the file manually and place it at "
            f"{destination}, then re-run."
        )
    response.raise_for_status()
    destination.parent.mkdir(parents=True, exist_ok=True)
    scratch = destination.with_suffix(destination.suffix + ".partial")
    with scratch.open("wb") as handle:
        for chunk in response.iter_content(1 << 20):
            handle.write(chunk)
    scratch.replace(destination)


def fetch_all(*, verify_only: bool = False) -> dict[str, dict]:
    """Download anything missing, verify everything present, return the manifest.

    Raises on any hash mismatch. Returns the manifest keyed by source key.
    """
    entries = read_manifest()
    deferred: list[str] = []
    for source in SOURCES:
        destination = raw_path(source.key)
        if not destination.exists():
            if source.manual:
                # Pin everything else first so a manual gap does not throw away
                # the provenance record for the sources that did arrive.
                deferred.append(
                    f"{source.key}: {destination} is missing and cannot be fetched "
                    f"automatically.\n{source.manual_instructions}"
                )
                continue
            if verify_only:
                raise ManualSourceMissing(
                    f"{source.key}: {destination} is missing (verify_only=True)."
                )
            print(f"[fetch] downloading {source.key} <- {source.url}")
            _download(source, destination)
        digest = _sha256(destination)
        recorded = entries.get(source.key)
        if recorded is None:
            entries[source.key] = {
                "key": source.key,
                "filename": source.filename,
                "url": source.url,
                "sha256": digest,
                "retrieved_utc": datetime.now(timezone.utc)
                .replace(microsecond=0)
                .isoformat()
                .replace("+00:00", "Z"),
                "release_label": source.release_label,
                "acquisition": "manual" if source.manual else "automatic",
            }
            print(f"[fetch] pinned {source.key} sha256={digest}")
        elif recorded["sha256"] != digest:
            raise SourceHashMismatch(
                f"{source.key}: {destination} has sha256 {digest}, manifest pins "
                f"{recorded['sha256']}. The upstream release changed or the file was "
                "edited. Resolve deliberately -- do not overwrite the manifest."
            )
        else:
            print(f"[fetch] verified {source.key} sha256={digest}")
    _write_manifest(entries)
    if deferred:
        raise ManualSourceMissing("\n\n".join(deferred))
    return entries


def require_manifest_entry(key: str) -> dict:
    entries = read_manifest()
    if key not in entries:
        raise MissingManifestEntry(
            f"{key} has no SOURCE_MANIFEST.yaml entry. Run fetch_source_files.py first."
        )
    return entries[key]


