ONET_TABLES = {
    "occupation_data": "Occupation Data.txt",
    "job_titles": "Job Titles.txt",
    "sample_of_reported_titles": "Sample of Reported Titles.txt",
}


def read_onet_table(name: str) -> pd.DataFrame:
    """Read one tab-delimited table straight out of the pinned O*NET zip."""
    member = ONET_TABLES[name]
    with zipfile.ZipFile(raw_path("onet_database")) as archive:
        candidates = [n for n in archive.namelist() if n.endswith("/" + member)]
        if not candidates:
            raise RuntimeError(f"{member} not present in the pinned O*NET archive")
        with archive.open(candidates[0]) as handle:
            return pd.read_csv(
                io.TextIOWrapper(handle, encoding="utf-8"),
                sep="\t",
                dtype=str,
                keep_default_na=False,
                na_values=[""],
            )


def read_onet_readme() -> str:
    with zipfile.ZipFile(raw_path("onet_database")) as archive:
        candidates = [n for n in archive.namelist() if n.lower().endswith("read me.txt")]
        if not candidates:
            return ""
        return archive.read(candidates[0]).decode("utf-8", errors="replace")


def read_all_occupations() -> pd.DataFrame:
    """The O*NET OnLine All Occupations export, the only source of ``Data-level``.

    ``Data-level`` marks whether O*NET publishes data for an occupation. Residual
    "All Other" buckets have it blank. The database bundle does not carry the
    column, which is why this export is pinned separately.
    """
    return pd.read_csv(
        raw_path("onet_all_occupations"), dtype=str, keep_default_na=False, na_values=[""]
    )


def read_bls_soc_structure() -> pd.DataFrame:
    """Parse the BLS SOC 2018 structure workbook into ``code``/``title``/``level``.

    The workbook has a preamble of title rows above a header row whose columns are
    the four level names plus a title column. The header row is located by content
    rather than by a fixed offset so a formatting change surfaces as a clear error
    instead of silently shifting every code by one row.
    """
    frame = pd.read_excel(raw_path("bls_soc_structure"), header=None, dtype=str)

    header_row = None
    for index, row in frame.iterrows():
        cells = [str(value).strip().casefold() for value in row.tolist() if pd.notna(value)]
        joined = " | ".join(cells)
        if "major group" in joined and "detailed occupation" in joined:
            header_row = index
            break
    if header_row is None:
        raise RuntimeError(
            "Could not locate the header row in the BLS SOC structure workbook. "
            "The layout changed; update read_bls_soc_structure rather than guessing."
        )

    header = [
        str(value).strip().casefold() if pd.notna(value) else ""
        for value in frame.iloc[header_row].tolist()
    ]
    level_columns: dict[str, int] = {}
    for position, name in enumerate(header):
        for level, marker in (
            ("major", "major group"),
            ("minor", "minor group"),
            ("broad", "broad group"),
            ("detailed", "detailed occupation"),
        ):
            if marker in name and level not in level_columns:
                level_columns[level] = position
    missing = {"major", "minor", "broad", "detailed"} - set(level_columns)
    if missing:
        raise RuntimeError(f"BLS structure workbook is missing level columns: {sorted(missing)}")

    # The title column sits immediately right of the four level columns and is
    # itself unlabelled in the header row, so it is located positionally.
    title_column = max(level_columns.values()) + 1
    if title_column >= frame.shape[1]:
        raise RuntimeError("BLS structure workbook has no title column after the level columns")

    records: list[dict[str, str]] = []
    for _, row in frame.iloc[header_row + 1 :].iterrows():
        values = row.tolist()
        title = values[title_column] if title_column < len(values) else None
        for level, column in level_columns.items():
            code = values[column] if column < len(values) else None
            if code is None or (isinstance(code, float) and pd.isna(code)):
                continue
            code = str(code).strip()
            if not code or code.casefold().startswith(("major", "minor", "broad", "detailed")):
                continue
            records.append(
                {
                    "code": code,
                    "title": ("" if title is None or pd.isna(title) else str(title).strip()),
                    "level": level,
                }
            )
    if not records:
        raise RuntimeError("Parsed zero rows from the BLS SOC structure workbook")
    return pd.DataFrame.from_records(records).drop_duplicates(subset=["code"], keep="first")


def read_cip_soc_crosswalk() -> pd.DataFrame:
    """The CIP-SOC sheet of the NCES crosswalk, columns renamed to snake_case."""
    frame = pd.read_excel(raw_path("cip_soc_crosswalk"), sheet_name="CIP-SOC", dtype=str)
    return frame.rename(
        columns={
            "CIP2020Code": "cip_code",
            "CIP2020Title": "cip_title",
            "SOC2018Code": "soc_code",
            "SOC2018Title": "soc_title",
        }
    )


def main() -> None:
    entries = fetch_all()
    print(f"\n{len(entries)} sources pinned in {MANIFEST_PATH}")


if __name__ == "__main__":
    main()
